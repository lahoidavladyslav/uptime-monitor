"""Build a realistic data set for performance work: N monitors, M checks spread over D days, K incidents.

Everything is generated by the database (`INSERT ... SELECT ... generate_series`, one statement per day), never by an
ORM loop: 5 million rows take minutes. The data is deterministic (`--seed`), so the numbers in docs/perf.md can be
reproduced. Down checks are exactly the ones that fall inside an incident window, like in real life.

NOTE: raw checks older than CHECK_RETENTION_DAYS are dropped by `manage_partitions`. When seeding 30 days, run the
stack with CHECK_RETENTION_DAYS=31 (docker-compose.perf.yml does), or the housekeeping will eat your data set.
"""

import math
from datetime import UTC, timedelta

from django.conf import settings
from django.contrib.auth import get_user_model
from django.core.management.base import BaseCommand, CommandError
from django.db import connection, transaction
from django.utils import timezone

from monitors import partitions, rollups
from monitors.models import Monitor

PREFIX = "perf-"
USERNAME = "perf"

# Incident windows are a pure function of (monitor index, k): start = day offset + hour offset, duration 10..109 min.
# The SAME expressions place the incident rows and decide which checks are down, so the two always agree.
WINDOWS_SQL = """
CREATE TEMP TABLE perf_windows ON COMMIT DROP AS
SELECT ids.monitor_id,
       %(start)s::timestamptz + make_interval(days => (m * 7 + k * 9) %% %(spread)s, hours => (m * 5 + k * 3) %% 20) AS start_at,
       %(start)s::timestamptz + make_interval(days => (m * 7 + k * 9) %% %(spread)s, hours => (m * 5 + k * 3) %% 20,
                                              mins => 10 + (m * 11 + k * 17) %% 100) AS end_at
FROM (SELECT (%(ids)s::bigint[])[g + 1] AS monitor_id, g AS m FROM generate_series(0, %(n)s - 1) g) ids
CROSS JOIN generate_series(0, %(per)s - 1) k
"""

CHECKS_SQL = """
INSERT INTO monitors_checkresult
    (monitor_id, checked_at, status_code, response_time_ms, is_up, error, region, in_maintenance, details)
SELECT x.monitor_id, x.ts,
       CASE WHEN x.up THEN 200 ELSE 503 END,
       CASE WHEN x.up THEN 50 + (random() * 400)::int END,
       x.up,
       CASE WHEN x.up THEN NULL ELSE 'HTTP 503' END,
       'eu', false,
       CASE WHEN x.up THEN '{}'::jsonb
            ELSE '{"type": "http_status", "status_code": 503, "message": "HTTP 503"}'::jsonb END
FROM (
    SELECT c.monitor_id, c.ts,
           NOT EXISTS (SELECT 1 FROM perf_windows w
                       WHERE w.monitor_id = c.monitor_id AND c.ts >= w.start_at AND c.ts < w.end_at) AS up
    FROM (
        SELECT (%(ids)s::bigint[])[(g %% %(n)s) + 1] AS monitor_id,
               %(start)s::timestamptz + make_interval(secs => (g / %(n)s) * %(step)s + random() * %(step)s) AS ts
        FROM generate_series(%(lo)s, %(hi)s - 1) g
    ) c
) x
"""

INCIDENTS_SQL = """
INSERT INTO monitors_incident (monitor_id, started_at, resolved_at, first_error, during_maintenance)
SELECT monitor_id, start_at, end_at, 'HTTP 503', false FROM perf_windows
"""


class Command(BaseCommand):
    help = "Seed monitors, raw checks (in SQL), incidents and rollups for performance measurements."

    def add_arguments(self, parser):
        parser.add_argument("--monitors", type=int, default=1000)
        parser.add_argument("--checks", type=int, default=5_000_000)
        parser.add_argument("--incidents", type=int, default=3000)
        parser.add_argument("--days", type=int, default=30)
        parser.add_argument("--seed", type=float, default=0.42, help="makes the data reproducible (0..1)")
        parser.add_argument("--clean", action="store_true", help="remove everything seed_volume created")

    def handle(self, *args, monitors, checks, incidents, days, seed, clean, **options):
        User = get_user_model()
        if clean:
            return self._clean(User)
        if not (monitors > 0 and checks >= monitors and days > 0 and incidents >= 0 and 0 <= seed <= 1):
            raise CommandError("need monitors > 0, checks >= monitors, days > 0, incidents >= 0, 0 <= seed <= 1")
        if Monitor.objects.filter(name__startswith=PREFIX).exists():
            raise CommandError("already seeded: run with --clean first (seeding twice would double the volume)")
        if days > settings.CHECK_RETENTION_DAYS:
            self.stderr.write(
                f"WARNING: --days {days} > CHECK_RETENTION_DAYS={settings.CHECK_RETENTION_DAYS}: manage_partitions will "
                f"drop the old days. Run the stack with CHECK_RETENTION_DAYS={days + 1}."
            )

        user, _ = User.objects.get_or_create(username=USERNAME, defaults={"email": "perf@example.com"})
        user.set_unusable_password()
        user.save(update_fields=["password"])
        Monitor.objects.bulk_create(
            [
                Monitor(
                    user=user, name=f"{PREFIX}{i:04d}", url=f"https://perf-{i:04d}.example.com/", interval_seconds=300
                )
                for i in range(monitors)
            ],
            batch_size=1000,
        )
        ids = list(
            Monitor.objects.filter(user=user, name__startswith=PREFIX).order_by("pk").values_list("pk", flat=True)
        )

        end = timezone.now().astimezone(UTC).replace(minute=0, second=0, microsecond=0)
        start = end - timedelta(days=days)
        for d in range(-1, days + 1):  # create the day partitions FIRST, so no row lands in the default partition
            partitions.ensure_partition((start + timedelta(days=d)).date())

        per_monitor = checks // monitors
        total = per_monitor * monitors
        step = days * 86400 / per_monitor  # seconds between one monitor's checks
        params = {"ids": ids, "n": monitors, "start": start, "step": step}
        windows_per_monitor = incidents // monitors
        spread = max(days - 1, 1)
        chunk = math.ceil(total / days)
        written = 0
        # one transaction: the temp table of incident windows lives as long as the checks that depend on it
        with transaction.atomic(), connection.cursor() as cur:
            cur.execute("SELECT setseed(%s)", [seed])
            cur.execute("DROP TABLE IF EXISTS perf_windows")  # ON COMMIT DROP does not fire inside an outer transaction
            if windows_per_monitor:
                cur.execute(WINDOWS_SQL, {**params, "per": windows_per_monitor, "spread": spread})
            else:
                cur.execute(
                    "CREATE TEMP TABLE perf_windows (monitor_id bigint, start_at timestamptz, end_at timestamptz) "
                    "ON COMMIT DROP"
                )
            cur.execute("CREATE INDEX ON perf_windows (monitor_id)")
            cur.execute(INCIDENTS_SQL)
            while written < total:
                hi = min(written + chunk, total)
                cur.execute(CHECKS_SQL, {**params, "lo": written, "hi": hi})
                written = hi
        self._status_page(user, ids)
        rollups.build(start, end + timedelta(days=1))
        with connection.cursor() as cur:
            cur.execute("ANALYZE monitors_checkresult")
            cur.execute("ANALYZE monitors_incident")
            cur.execute("ANALYZE monitors_checkrolluphourly")
        self.stdout.write(
            self.style.SUCCESS(
                f"Seeded {monitors} monitors, {total} checks over {days} days, {windows_per_monitor * monitors} incidents."
            )
        )

    @staticmethod
    def _status_page(user, ids):
        """A public page over the first 50 monitors: the public-page scenario of perf_report needs one."""
        from monitors.models import StatusPage

        first = ids[:50]
        Monitor.objects.filter(pk__in=first).update(is_public=True)
        page = StatusPage.objects.create(user=user, title="Perf status", slug="perf-status", is_public=True)
        page.monitors.set(first)

    def _clean(self, User):
        monitors = Monitor.objects.filter(name__startswith=PREFIX)
        ids = list(monitors.values_list("pk", flat=True))
        with connection.cursor() as cur:  # a plain DELETE per partition would be the slow path the project avoids
            cur.execute("DELETE FROM monitors_checkresult WHERE monitor_id = ANY(%s)", [ids])
        monitors.delete()
        User.objects.filter(username=USERNAME).delete()
        self.stdout.write("Removed the seeded data.")
